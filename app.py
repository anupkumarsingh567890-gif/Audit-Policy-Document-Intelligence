"""APDIS — Streamlit application (built only from native Streamlit components).

Run:  streamlit run app.py
"""

from __future__ import annotations

import re

import streamlit as st

from src.chatbot.assistant import (
    MODE_RAG,
    MODE_RETRIEVAL,
    NO_RESULTS_MESSAGE,
    APDISAssistant,
)
from src.utils import config

st.set_page_config(
    page_title="APDIS — Intelligent Document Analysis",
    page_icon=":material/verified_user:",
    layout="wide",
    initial_sidebar_state="expanded",
)

SUGGESTIONS = [
    "Within how many days must an NBFC report fraud to RBI?",
    "What did CAG find about BSNL tower properties?",
    "Which listed entities must submit a BRSR report?",
    "How are internal audit observations graded by severity?",
]
AVATARS = {"user": ":material/person:", "assistant": ":material/auto_awesome:"}
_CITE_RE = re.compile(r"\[(\d+(?:\s*,\s*\d+)*)\]")


def md_escape(text: str) -> str:
    """Escape characters that Markdown would otherwise interpret (e.g. _ in file names)."""
    return re.sub(r"([\\`*_{}\[\]<>#|~$])", r"\\\1", text)


def format_answer(text: str) -> str:
    """Show inline citations like [1] or [1, 3] as small blue badges."""
    text = text.replace("$", "\\$")  # stop "$5 ... $10" being rendered as maths
    return _CITE_RE.sub(lambda m: " ".join(f":blue-badge[{n.strip()}]" for n in m.group(1).split(",")), text)


def render_sources(results) -> None:
    if not results:
        return
    badges = " ".join(
        f":blue-badge[**{i}** · :material/description: {md_escape(r.source)} · p.{r.page}]"
        for i, r in enumerate(results, 1)
    )
    st.markdown(f":gray[**Sources**]  \n{badges}")
    with st.expander(f"View the {len(results)} retrieved passages", icon=":material/menu_book:"):
        for i, r in enumerate(results, 1):
            st.markdown(f"**[{i}] {md_escape(r.source)} — Page {r.page}** · similarity `{r.score:.3f}`")
            st.caption(r.text)


def model_line(model: str | None) -> None:
    if model:
        st.caption(f":material/bolt: Generated by {model}")


@st.cache_resource(show_spinner="Loading embedding model and vector database…")
def get_assistant() -> APDISAssistant:
    return APDISAssistant()


assistant = get_assistant()
st.session_state.setdefault("messages", [])
st.session_state.setdefault("processed_uploads", set())

# ------------------------------------------------------------------ sidebar
with st.sidebar:
    st.title(":material/verified_user: APDIS")
    st.caption("**Audit & Policy Document Intelligence System** — answers from your audit, policy, risk and compliance PDFs, each with page-level citations.")

    st.divider()
    st.subheader(":material/upload_file: Upload documents")
    uploads = st.file_uploader(
        "Drag and drop PDF files", type=["pdf"], accept_multiple_files=True, label_visibility="collapsed"
    )
    if uploads:
        new_files = [f for f in uploads if (f.name, f.size) not in st.session_state.processed_uploads]
        if new_files and st.button(
            f"Process {len(new_files)} file(s)", type="primary", icon=":material/bolt:", width="stretch"
        ):
            progress = st.progress(0.0)
            for i, f in enumerate(new_files, 1):
                with st.spinner(f"Processing {f.name}…"):
                    try:
                        report = assistant.ingest_bytes(f.getvalue(), f.name)
                        (st.warning if report.num_chunks == 0 else st.success)(report.message)
                        st.session_state.processed_uploads.add((f.name, f.size))
                    except Exception as exc:  # noqa: BLE001
                        st.error(f"{f.name}: {exc}")
                progress.progress(i / len(new_files))
            st.rerun()

    docs = assistant.documents()
    st.divider()
    st.subheader(f":material/library_books: Knowledge base  :blue-badge[{len(docs)}]")
    if docs:
        for i, (name, n_chunks) in enumerate(docs.items()):
            with st.container(border=True):
                c1, c2 = st.columns([6, 1], vertical_alignment="center")
                c1.markdown(f"**{md_escape(name)}**  \n:gray[:material/description: {n_chunks:,} chunks]")
                if c2.button("", icon=":material/close:", key=f"del_{i}", type="tertiary", help=f"Remove {name}"):
                    assistant.remove_document(name)
                    st.rerun()
    else:
        st.info("No documents yet. Upload PDFs above, or run `python scripts/ingest.py`.", icon=":material/info:")

    st.divider()
    st.subheader(":material/tune: Settings")
    mode_label = st.radio(
        "Answer mode",
        ["Gemini RAG", "Semantic Retrieval (no LLM)"],
        captions=["AI writes a cited answer", "Shows the matching passages"],
    )
    mode = MODE_RAG if mode_label == "Gemini RAG" else MODE_RETRIEVAL
    top_k = st.slider("Passages to retrieve (top-k)", 1, 10, config.TOP_K)
    doc_filter = st.multiselect("Search only in", list(docs.keys()), placeholder="All documents")

    if st.session_state.messages and st.button("Clear chat", icon=":material/delete_sweep:", width="stretch"):
        st.session_state.messages = []
        st.rerun()

    st.caption(f"LLM: `{config.GEMINI_MODEL}` · Embeddings: `{config.EMBEDDING_MODEL.split('/')[-1]}` · ChromaDB")

# ------------------------------------------------------------------ header
if config.GEMINI_API_KEY:
    st.badge("AI System Online", icon=":material/check_circle:", color="green")
else:
    st.badge("Retrieval only — add GEMINI_API_KEY to .env", icon=":material/warning:", color="orange")
st.title("Intelligent Document Analysis")
st.markdown(":gray[Your AI-powered workspace for audit, risk, policy, and compliance intelligence.]")

# ------------------------------------------------------------------ KPI cards
k1, k2, k3 = st.columns(3)
k1.metric(":material/description: Total documents", len(docs), border=True, help="PDFs in the knowledge base")
k2.metric(":material/stacks: Indexed chunks", f"{sum(docs.values()):,}", border=True, help="Searchable passages, each with its page number")
k3.metric(
    ":material/bolt: Active mode",
    "Gemini RAG" if mode == MODE_RAG else "Retrieval",
    border=True,
    help=f"Model: {config.GEMINI_MODEL}" if mode == MODE_RAG else "Semantic search only, no LLM",
)

# ------------------------------------------------------------------ chat history
for msg in st.session_state.messages:
    with st.chat_message(msg["role"], avatar=AVATARS[msg["role"]]):
        if msg["role"] == "assistant":
            st.markdown(format_answer(msg["content"]))
            model_line(msg.get("model"))
            render_sources(msg.get("results", []))
        else:
            st.markdown(msg["content"])

# ------------------------------------------------------------------ empty state
pending_question = st.session_state.pop("pending_question", None)
if not docs and not st.session_state.messages:
    st.info("Start by uploading PDF documents in the sidebar.", icon=":material/upload_file:")
elif not st.session_state.messages and not pending_question:
    st.subheader(":material/lightbulb: Try asking")
    cols = st.columns(2)
    for i, q in enumerate(SUGGESTIONS):
        if cols[i % 2].button(q, key=f"suggest_{i}", icon=":material/arrow_outward:", width="stretch"):
            st.session_state.pending_question = q
            st.rerun()

# ------------------------------------------------------------------ new question
question = st.chat_input(
    "Ask anything about your audit, policy, risk, or compliance documents...", disabled=not docs
) or pending_question

if question:
    st.session_state.messages.append({"role": "user", "content": question})
    with st.chat_message("user", avatar=AVATARS["user"]):
        st.markdown(question)

    with st.chat_message("assistant", avatar=AVATARS["assistant"]):
        try:
            with st.spinner("Searching documents…"):
                results, refs = assistant.retrieve(question, top_k=top_k, source_filter=doc_filter or None)

            model = None
            if not results:
                answer = NO_RESULTS_MESSAGE
                st.markdown(answer)
            elif mode == MODE_RETRIEVAL:
                answer = assistant.format_passages(results)
                st.markdown(format_answer(answer))
            else:
                # Stream Gemini's answer: a status line until the first words arrive, then live text
                box = st.empty()
                box.caption(":material/hourglass_top: Reading the passages and writing an answer…")
                answer = ""
                for piece in assistant.stream_answer(question, results):
                    answer += piece
                    box.markdown(format_answer(answer) + " ▌")
                box.markdown(format_answer(answer))
                model = assistant.llm.last_model_used
                model_line(model)

            render_sources(results)
            st.session_state.messages.append(
                {"role": "assistant", "content": answer, "model": model, "results": results, "refs": refs}
            )
        except Exception as exc:  # noqa: BLE001
            st.error(str(exc))